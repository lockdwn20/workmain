@gdocs.command("upload-all")
@click.option("--date", "date_str", type=str, default=None,
              help="Target date YYYYMMDD. Default: today.")
@click.option("--dry-run", is_flag=True, default=False,
              help="Show what would be uploaded — no Drive writes.")
@click.option("--force", is_flag=True, default=False,
              help="Re-upload even if already uploaded for this date.")
@click.pass_context
def gdocs_upload_all(ctx, date_str: Optional[str], dry_run: bool, force: bool):
    """
    Upload notes, report, and Clockify PDF to Drive in sequence.

    Runs upload-notes, upload-report, upload-clockify in order.
    On failure of any step, prompts whether to continue with remaining uploads.

    \b
    Examples:
      workmain gdocs upload-all
      workmain gdocs upload-all --date 20260308
      workmain gdocs upload-all --dry-run
    """
    _require_env_root()
    _require_auth()

    target_date = _parse_date_arg(date_str)
    root_name   = os.environ.get("GDRIVE_TIMECARDS_ROOT", "Timecards")
    period      = target_date.strftime("%Y%m")

    results: dict = {}  # step -> (success, filename or error)

    def _run_step(step_name: str, filename: str, upload_fn) -> bool:
        try:
            upload_fn()
            results[step_name] = (True, filename)
            return True
        except SystemExit:
            results[step_name] = (False, "upload failed")
            return False
        except Exception as exc:
            results[step_name] = (False, str(exc))
            return False

    # --- Notes ---
    notes_filename = f"Daily_Notes_{target_date.strftime('%Y%m%d')}.md"

    def _upload_notes():
        ctx.invoke(
            gdocs_upload_notes,
            date_str=target_date.strftime("%Y%m%d"),
            dry_run=dry_run,
            force=force,
        )

    ok = _run_step("Notes", notes_filename, _upload_notes)
    if not ok:
        ans = click.prompt(
            "Continue with remaining uploads? [Y/n]",
            default="Y",
            show_default=False,
        ).strip().lower()
        if ans not in ("", "y", "yes"):
            _print_summary(results, target_date, root_name, period, dry_run)
            return

    # --- Report ---
    report_filename = f"daily_internal_{target_date.strftime('%Y-%m-%d')}.md"

    def _upload_report():
        ctx.invoke(
            gdocs_upload_report,
            date_str=target_date.strftime("%Y%m%d"),
            dry_run=dry_run,
            force=force,
        )

    ok = _run_step("Report", report_filename, _upload_report)
    if not ok:
        ans = click.prompt(
            "Continue with remaining uploads? [Y/n]",
            default="Y",
            show_default=False,
        ).strip().lower()
        if ans not in ("", "y", "yes"):
            _print_summary(results, target_date, root_name, period, dry_run)
            return

    # --- Clockify ---
    clockify_filename = f"Clockify_{target_date.strftime('%Y%m%d')}.pdf"

    def _upload_clockify():
        ctx.invoke(
            gdocs_upload_clockify,
            date_str=target_date.strftime("%Y%m%d"),
            dry_run=dry_run,
            force=force,
        )

    _run_step("Clockify", clockify_filename, _upload_clockify)

    _print_summary(results, target_date, root_name, period, dry_run)


def _print_summary(
    results: dict, target_date: date, root_name: str, period: str, dry_run: bool
) -> None:
    """Print the upload summary table."""
    prefix = "[DRY RUN] " if dry_run else ""
    console.print(f"\n[bold]{prefix}Upload Summary — {target_date}[/bold]")
    labels = {
        "Notes":    (f"{root_name}/{period}/Raw_Notes/",  results.get("Notes")),
        "Report":   (f"{root_name}/{period}/Reports/",    results.get("Report")),
        "Clockify": (f"{root_name}/{period}/Clockify/",   results.get("Clockify")),
    }
    for label, (dest, result) in labels.items():
        if result is None:
            icon = "[yellow]–[/yellow]"
            detail = "skipped"
        elif result[0]:
            icon = "[green]✓[/green]"
            detail = f"→ {dest}{result[1]}"
        else:
            icon = "[red]✗[/red]"
            detail = result[1]
        console.print(f"  {icon} {label:<10} {detail}")
    console.print()
