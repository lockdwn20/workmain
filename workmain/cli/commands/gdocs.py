@gdocs.command("status")
def gdocs_status():
    """
    Show Google Drive integration status.

    Displays authentication state, cached folder IDs, and recent upload history.

    \b
    Example:
      workmain gdocs status
    """
    root_name = os.environ.get("GDRIVE_TIMECARDS_ROOT", "(not set)")
    authed = is_authenticated()

    console.print()
    console.print(Panel.fit(
        "Google Drive Integration",
        border_style="cyan"
    ))
    console.print(Rule(style="dim"))

    auth_icon = "[green]✓ Authenticated[/green]" if authed else "[red]✗ Not authenticated[/red]"
    console.print(f"Auth          {auth_icon}")

    if not authed:
        console.print("\nRun: [bold]workmain gdocs auth[/bold]\n")
        return

    from workmain.integrations.gdrive.auth import TOKEN_PATH
    console.print(f"Token path    [dim]{TOKEN_PATH}[/dim]")
    console.print(f"Root folder   [dim]{root_name} (GDRIVE_TIMECARDS_ROOT)[/dim]")

    # Cached folders
    cache = folder_cache.load_cache()
    if cache:
        console.print()
        console.print("[bold]Cached Folders[/bold]")
        for period, entries in sorted(cache.items()):
            for sub, fid in entries.items():
                label = "root" if sub == "root" else sub
                console.print(f"  {period}  {label:<12} → {fid}")

    # Recent uploads
    db = get_db()
    session = db.get_session()
    try:
        repo = GDriveRepository(session)
        recent = repo.get_recent_uploads(limit=5)
        console.print()
        console.print("[bold]Recent Uploads (last 5)[/bold]")
        if recent:
            for rec in recent:
                console.print(
                    f"  {rec.upload_date}  {rec.upload_type:<10} {rec.filename}"
                )
        else:
            console.print("  [dim](none yet)[/dim]")
    finally:
        session.close()

    console.print()


