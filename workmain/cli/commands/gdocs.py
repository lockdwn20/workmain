def _parse_date_arg(date_str: Optional[str]) -> date:
    """Parse YYYYMMDD string to date, defaulting to today."""
    if date_str is None:
        return date.today()
    try:
        return datetime.strptime(date_str, "%Y%m%d").date()
    except ValueError:
        raise click.BadParameter(
            f"Invalid date '{date_str}'. Expected format: YYYYMMDD (e.g. 20260309)."
        )


def _require_env_root() -> str:
    """Return GDRIVE_TIMECARDS_ROOT or abort with a clear message."""
    root = os.environ.get("GDRIVE_TIMECARDS_ROOT", "").strip()
    if not root:
        console.print(
            "\n[red]✗ GDRIVE_TIMECARDS_ROOT is not set.[/red] "
            "Add it to your .env file.\n"
        )
        sys.exit(1)
    return root


def _require_auth() -> None:
    """Abort with a clear message if not authenticated."""
    if not is_authenticated():
        console.print(
            "\n[red]✗ Not authenticated.[/red] "
            "Run: [bold]workmain gdocs auth[/bold]\n"
        )
        sys.exit(1)


def _get_client() -> GDriveClient:
    """Build an authenticated GDriveClient, handling auth errors."""
    try:
        svc = get_service()
        return GDriveClient(svc)
    except GDriveAuthError as exc:
        console.print(f"\n[red]✗ Auth error:[/red] {exc}\n")
        sys.exit(1)


def _format_notes_markdown(notes: list, target_date: date) -> str:
    """
    Format a list of Note objects as the canonical §3.8 markdown.

    Format:
        # Daily Notes — YYYY-MM-DD

        ## [tag] HH:MM
        Note content here.

        ---
        *Generated by WorkmAIn on YYYY-MM-DD HH:MM*

    Rules:
    - Notes ordered by created_at ascending (already sorted by repo)
    - Tags shown as full display names in brackets
    - Multiple tags: [tag1] [tag2] HH:MM
    - Time in 24-hour format (HH:MM)
    - Empty body: included with empty line
    """
    date_str = target_date.strftime("%Y-%m-%d")
    lines = [f"# Daily Notes — {date_str}", ""]

    for note in notes:
        tags = note.tags or []
        tag_str = " ".join(f"[{t}]" for t in tags) if tags else "[internal-only]"
        time_str = note.created_at.strftime("%H:%M") if note.created_at else "00:00"
        lines.append(f"## {tag_str} {time_str}")
        lines.append(note.content if note.content else "")
        lines.append("")

    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines.append("---")
    lines.append(f"*Generated by WorkmAIn on {now}*")

    return "\n".join(lines)


