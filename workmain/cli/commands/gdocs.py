@gdocs.command("auth")
@click.option("--reauth", is_flag=True, default=False,
              help="Force re-authentication even if a valid token exists.")
def gdocs_auth(reauth: bool):
    """
    Authenticate with Google Drive.

    Uses a WSL-safe console flow (copy-paste URL + auth code — no browser spawn).
    Reuses an existing token if valid unless --reauth is passed.
    After auth, verifies the current month's folder structure in Drive.

    \b
    Examples:
      workmain gdocs auth
      workmain gdocs auth --reauth
    """
    _require_env_root()

    if not reauth and is_authenticated():
        console.print(
            "\n[green]✓ Already authenticated.[/green] "
            "Use [bold]--reauth[/bold] to refresh.\n"
        )
        return

    console.print("\n[cyan]Starting Google Drive authentication...[/cyan]")
    console.print("[dim]A URL will be printed. Open it in your browser, sign in,\nthen paste the authorization code below.[/dim]\n")

    try:
        svc = get_service()
        client = GDriveClient(svc)
    except GDriveAuthError as exc:
        console.print(f"\n[red]✗ Authentication failed:[/red] {exc}\n")
        sys.exit(1)

    # Cache folder structure for current month
    period = date.today().strftime("%Y%m")
    try:
        ids = client.ensure_period_structure(period)
        console.print("\n[green]✓ Authentication complete. Drive folder structure verified.[/green]")
        console.print(f"  [dim]Period: {period}[/dim]")
        for key, fid in ids.items():
            console.print(f"  [dim]{key:<12} → {fid}[/dim]")
        console.print()
    except GDriveClientError as exc:
        console.print(f"\n[red]✗ Drive API error:[/red] {exc}\n")
        sys.exit(1)


